import type { TileGraph } from './graph';

/** Hyperboloid model: points (x, y, z) with x² + y² − z² = −1, z > 0. Matrices are row-major 3x3 Lorentz transforms. */
export type Vec3 = [number, number, number];
export type Mat3 = number[]; // length 9, row-major

export const identity = (): Mat3 => [1, 0, 0, 0, 1, 0, 0, 0, 1];

export function mul(a: Mat3, b: Mat3): Mat3 {
  const o = new Array<number>(9);
  for (let i = 0; i < 3; i++)
    for (let j = 0; j < 3; j++) o[i * 3 + j] = a[i * 3] * b[j] + a[i * 3 + 1] * b[3 + j] + a[i * 3 + 2] * b[6 + j];
  return o;
}

export const apply = (m: Mat3, v: Vec3): Vec3 => [
  m[0] * v[0] + m[1] * v[1] + m[2] * v[2],
  m[3] * v[0] + m[4] * v[1] + m[5] * v[2],
  m[6] * v[0] + m[7] * v[1] + m[8] * v[2],
];

export const rot = (t: number): Mat3 => [Math.cos(t), -Math.sin(t), 0, Math.sin(t), Math.cos(t), 0, 0, 0, 1];

/** Boost by hyperbolic distance d in direction angle `dir`. */
export function boost(d: number, dir = 0): Mat3 {
  const bx: Mat3 = [Math.cosh(d), 0, Math.sinh(d), 0, 1, 0, Math.sinh(d), 0, Math.cosh(d)];
  return mul(rot(dir), mul(bx, rot(-dir)));
}

/** Boost that carries hyperboloid point p to the origin (0,0,1). p = boost(d, θ)·origin with d = dist(origin, p),
 *  θ = angle of (x, y), so the answer is that boost's inverse: boost(−d, θ). */
export function boostToOrigin(p: Vec3): Mat3 {
  return boost(-Math.acosh(Math.max(1, p[2])), Math.atan2(p[1], p[0]));
}

/** Lorentz inverse: η Mᵀ η with η = diag(1,1,−1). */
export function inverse(m: Mat3): Mat3 {
  const t = [m[0], m[3], m[6], m[1], m[4], m[7], m[2], m[5], m[8]];
  const s = [1, 1, -1];
  return t.map((v, k) => v * s[Math.floor(k / 3)] * s[k % 3]);
}

const mdot = (a: Vec3, b: Vec3) => a[0] * b[0] + a[1] * b[1] - a[2] * b[2];

/** Pull a point back onto the hyperboloid. */
export function normalize(v: Vec3): Vec3 {
  const n = Math.sqrt(Math.max(1e-12, -mdot(v, v)));
  return [v[0] / n, v[1] / n, v[2] / n];
}

/** Point along the geodesic P→Q at parameter t (interpolate in ambient space, renormalise). */
export const geodesic = (p: Vec3, q: Vec3, t: number): Vec3 =>
  normalize([p[0] + (q[0] - p[0]) * t, p[1] + (q[1] - p[1]) * t, p[2] + (q[2] - p[2]) * t]);

export const toDisk = (v: Vec3): [number, number] => [v[0] / (1 + v[2]), v[1] / (1 + v[2])];

export const dist = (a: Vec3, b: Vec3) => Math.acosh(Math.max(1, -mdot(a, b)));

/** Re-orthonormalise a drifting Lorentz matrix (Gram–Schmidt with the Minkowski metric, on columns). */
export function orthonormalize(m: Mat3): Mat3 {
  const col = (j: number): Vec3 => [m[j], m[3 + j], m[6 + j]];
  const c2 = normalize(col(2));
  let c0 = col(0);
  const p0 = mdot(c0, c2);
  c0 = [c0[0] + p0 * c2[0], c0[1] + p0 * c2[1], c0[2] + p0 * c2[2]];
  const n0 = Math.sqrt(mdot(c0, c0));
  c0 = [c0[0] / n0, c0[1] / n0, c0[2] / n0];
  let c1 = col(1);
  const p1a = mdot(c1, c2), p1b = mdot(c1, c0);
  c1 = [c1[0] + p1a * c2[0] - p1b * c0[0], c1[1] + p1a * c2[1] - p1b * c0[1], c1[2] + p1a * c2[2] - p1b * c0[2]];
  const n1 = Math.sqrt(mdot(c1, c1));
  c1 = [c1[0] / n1, c1[1] / n1, c1[2] / n1];
  return [c0[0], c1[0], c2[0], c0[1], c1[1], c2[1], c0[2], c1[2], c2[2]];
}

export interface HyperBoard extends TileGraph {
  centers: Vec3[];
  /** polygon vertices per tile, in order around the tile */
  verts: Vec3[][];
}

/** {p,q} tiling out to graph radius `radius`, generated by BFS of edge reflections from a centred p-gon. */
export function hyperGraph(radius: number, p = 7, q = 3): HyperBoard {
  const R = Math.acosh(1 / (Math.tan(Math.PI / p) * Math.tan(Math.PI / q))); // circumradius
  const a = Math.acosh(Math.cos(Math.PI / q) / Math.sin(Math.PI / p)); // inradius
  const base: Vec3[] = Array.from({ length: p }, (_, k) => {
    const t = (2 * Math.PI * k) / p;
    return [Math.sinh(R) * Math.cos(t), Math.sinh(R) * Math.sin(t), Math.cosh(R)];
  });
  // Neighbour across edge k: rotate to the edge midpoint direction, boost by twice the inradius.
  const step = Array.from({ length: p }, (_, k) => mul(rot(((2 * k + 1) * Math.PI) / p), boost(2 * a)));

  const xf: Mat3[] = [identity()];
  const centers: Vec3[] = [[0, 0, 1]];
  const ring = [0];
  const neighbours: number[][] = [[]];
  const find = (c: Vec3) => centers.findIndex((o) => dist(o, c) < 1e-4);

  for (let i = 0; i < xf.length; i++) {
    for (const s of step) {
      const m = mul(xf[i], s);
      const c = apply(m, [0, 0, 1]);
      let j = find(c);
      if (j < 0) {
        if (ring[i] + 1 > radius) continue;
        j = xf.length;
        xf.push(m);
        centers.push(c);
        ring.push(ring[i] + 1);
        neighbours.push([]);
      }
      if (!neighbours[i].includes(j)) neighbours[i].push(j);
      if (!neighbours[j].includes(i)) neighbours[j].push(i);
    }
  }
  return { ring, neighbours, centers, verts: xf.map((m) => base.map((v) => apply(m, v))) };
}
